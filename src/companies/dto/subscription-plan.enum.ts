/**
 * Enum que representa los planes de suscripción disponibles para empresas.
 */
export enum SubscriptionPlan {
  /**
   * Plan básico con funcionalidades limitadas.
   */
  FREE = 'FREE',
  
  /**
   * Plan estándar para pequeñas y medianas empresas.
   */
  STANDARD = 'STANDARD',
  
  /**
   * Plan completo con todas las funcionalidades.
   */
  PREMIUM = 'PREMIUM',
} 